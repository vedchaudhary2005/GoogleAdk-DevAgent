import os
import sys
from dotenv import load_dotenv

from google.adk.agents import BaseAgent, LlmAgent, LoopAgent
from google.adk.agents.invocation_context import InvocationContext
from google.adk.agents.readonly_context import ReadonlyContext
from google.adk.events import Event, EventActions
from google.adk.models.lite_llm import LiteLlm
from google.adk.tools.mcp_tool import McpToolset, StdioConnectionParams
from google.genai import types
from mcp import StdioServerParameters
from typing import AsyncGenerator


# 1. CONFIGURATION

BASE_DIR = os.path.dirname(os.path.abspath(__file__))

load_dotenv(os.path.join(BASE_DIR, ".env"))

MODEL_NAME = os.getenv("MODEL_NAME", "groq/openai/gpt-oss-120b")
MODEL = LiteLlm(model=MODEL_NAME)

REQUIRE_CONFIRMATION = os.getenv("REQUIRE_CONFIRMATION", "false").lower() in ("true", "1", "yes")


def set_agent_model(model_name: str) -> LiteLlm:
    """Dynamically set the model for all LLM agents in the hierarchy."""
    global MODEL, MODEL_NAME
    MODEL_NAME = model_name
    MODEL = LiteLlm(model=model_name)
    root_agent.model = MODEL
    writer_agent.model = MODEL
    reviewer_agent.model = MODEL
    return MODEL


# 2. MCP SERVER CONNECTION

mcp_server_params = StdioConnectionParams(
    server_params=StdioServerParameters(
        command=sys.executable,
        args=[
            os.path.join(BASE_DIR, "mcp_server.py")
        ]
    )
)

mcp_tools = McpToolset(
    connection_params=mcp_server_params,
    require_confirmation=REQUIRE_CONFIRMATION
)


# 3. WRITER DYNAMIC INSTRUCTION

def writer_instruction(context: ReadonlyContext) -> str:
    feedback = context.state.get("review_feedback", "")

    if feedback:
        feedback_section = f"""
        PREVIOUS REVIEWER FEEDBACK:
        {feedback}

        You must improve your previous code based on this feedback.
        Do not ignore the reviewer's corrections.
        """
    else:
        feedback_section = """
        This is the first iteration.
        Create the initial solution based on the user's request.
        """

    return f"""
    You are a senior software engineer.

    Your responsibilities:
    1. Understand the user's programming task.
    2. Write clean, readable and maintainable code with proper docstrings and error handling.
    3. Use the save_code_to_file tool to save the code into the workspace.
    4. Once save_code_to_file succeeds, do not make repetitive tool calls. Return the complete updated code in your final text response.
    5. Never claim that a file was saved unless save_code_to_file confirms it.

    {feedback_section}

    If you are revising code, preserve working functionality.
    Explain what you changed and why.

    Return the complete updated code in your final response.
    """


# 4. WRITER AGENT

writer_agent = LlmAgent(
    name="writer_agent",
    model=MODEL,
    description=(
        "Writes, modifies and saves production-oriented code "
        "using MCP developer tools."
    ),
    instruction=writer_instruction,
    tools=[
        mcp_tools
    ],
    output_key="generated_code"
)


# 5. REVIEWER AGENT

def reviewer_instruction(context: ReadonlyContext) -> str:
    generated_code = context.state.get("generated_code", "")

    if not generated_code:
        return """
        The Writer Agent did not provide generated code.
        Report: CHANGES_REQUIRED: Generated code is missing.
        Do not invent or generate code yourself.
        """

    return f"""
    You are a senior code reviewer.

    Review the following code generated by the Writer Agent:

    {generated_code}

    Check:
    1. Syntax and runtime errors.
    2. Incorrect logic or missing operations.
    3. Missing imports and dependencies.
    4. Security vulnerabilities.
    5. Error handling (e.g. division by zero).
    6. Code quality and maintainability.

    FORMAT REQUIREMENT:
    Your response MUST start with either:
    "APPROVED: <summary of why the code is approved>"
    OR
    "CHANGES_REQUIRED: <list of specific issues for writer to fix>"

    If the code is functionally correct and has no major bugs or security issues, approve it.
    Do not rewrite the entire project unnecessarily.
    """


reviewer_agent = LlmAgent(
    name="reviewer_agent",
    model=MODEL,
    description=(
        "Reviews generated code and identifies bugs, "
        "security issues and improvements."
    ),
    instruction=reviewer_instruction,
    output_key="review_feedback",
    include_contents="none"
)


# 6. APPROVAL CHECKER (Custom BaseAgent)

class ApprovalChecker(BaseAgent):
    """Checks if the reviewer approved the code. If approved, escalates to exit the loop."""

    async def _run_async_impl(
        self, ctx: InvocationContext
    ) -> AsyncGenerator[Event, None]:
        feedback = ctx.session.state.get("review_feedback", "")
        is_approved = feedback.strip().upper().startswith("APPROVED")

        if is_approved:
            yield Event(
                author=self.name,
                actions=EventActions(escalate=True),
                content=types.Content(
                    role="model",
                    parts=[types.Part.from_text(text="Reviewer APPROVED: Code refinement loop complete.")]
                )
            )
        else:
            yield Event(
                author=self.name,
                actions=EventActions(escalate=False),
                content=types.Content(
                    role="model",
                    parts=[types.Part.from_text(text="Reviewer requested changes. Continuing refinement loop.")]
                )
            )


approval_checker = ApprovalChecker(name="approval_checker")


def reset_loop_state(callback_context) -> None:
    """Initializes/resets state for the code loop."""
    callback_context.state["generated_code"] = ""
    callback_context.state["review_feedback"] = ""
    return None


# 7. REFINEMENT LOOP

code_loop = LoopAgent(
    name="code_loop",
    sub_agents=[
        writer_agent,
        reviewer_agent,
        approval_checker
    ],
    max_iterations=3,
    before_agent_callback=reset_loop_state
)


# 8. ROOT AGENT

root_agent = LlmAgent(
    name="root_agent",
    model=MODEL,
    description="Main coordinator for DevAgent Enterprise.",
    instruction="""
You are DevAgent Enterprise, an AI software development assistant.

SCOPE:
You must help with:
- Programming and code generation.
- Debugging and code review.
- Software architecture.
- Programming documentation and tutorials.
- Searching the web for programming-related information.
- Explaining programming concepts and libraries.

GUARDRAILS:
- Refuse requests unrelated to software development.
- Programming-related web searches are ALLOWED.
- Never refuse a programming documentation search just because
  the user asks to search the web.
- Never claim a tool was executed unless it actually was.

DELEGATION:
For coding, debugging, code review and programming research tasks,
delegate to code_loop.

The Writer Agent can use MCP tools including save_code_to_file and web_search.
The Reviewer Agent reviews generated code.
The Approval Checker verifies if the review passed.
""",
    sub_agents=[
        code_loop
    ]
)
